"""Formatted Excel workbook (openpyxl). The input data file is never modified.

Sheets
    About                 data status, disclaimer, units
    Raw_Financial_Data    input statements exactly as loaded
    Calculated_Ratios     ratios with a status column for each
    Ratio_Flags           undefined / not-applicable ratios explained
    Health_Scores         dimension and overall scores
    Altman_Z              variant, inputs X1..X5, score and zone
    Company_Comparison    latest common year, side by side
    Stress_Testing        every company, latest year, all scenarios
    Validation            data checks
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from . import config as C
from .company_comparison import comparison_table
from .pipeline import Analysis
from .stress_testing import run_stress

HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(color="FFFFFF", bold=True)
BANNER_FONT = Font(color="B42318", bold=True)


def _format_sheet(ws, df: pd.DataFrame, percent_cols: set[str], ratio_cols: set[str], money_cols: set[str],
                  start_row: int = 1) -> None:
    for j, col in enumerate(df.columns, start=1):
        cell = ws.cell(row=start_row, column=j)
        cell.fill, cell.font = HEADER_FILL, HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        fmt = ("0.0%" if col in percent_cols else "0.00" if col in ratio_cols
               else "#,##0.00" if col in money_cols else None)
        if fmt:
            for i in range(start_row + 1, start_row + 1 + len(df)):
                ws.cell(row=i, column=j).number_format = fmt
        width = max(len(str(col)), *(len(str(v)) for v in df[col].head(200))) if len(df) else len(str(col))
        ws.column_dimensions[get_column_letter(j)].width = min(max(10, width + 2), 48)
    ws.freeze_panes = ws.cell(row=start_row + 1, column=2)


def export_excel(a: Analysis, path: Path | str, scenarios: list[C.StressScenario] | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    money = set(C.ALL_ITEMS) | {"total_debt", "net_debt", "free_cash_flow", "working_capital",
                                "average_total_assets", "average_total_equity"}
    pct = {k for k in C.PERCENT_RATIOS}
    ratio_keys = set(C.RATIOS) - pct

    ratio_cols = ["company", "sector", "fiscal_year", "total_debt", "net_debt", "free_cash_flow", "working_capital"]
    for k in C.RATIOS:
        ratio_cols += [k, f"{k}__status"]
    ratios = a.ratios[ratio_cols].rename(columns={f"{k}__status": f"{k} status" for k in C.RATIOS})

    scores = a.scores[["company", "sector", "fiscal_year", "health_score", "risk_category", "weight_coverage",
                       "incomplete"] + [f"score_{d}" for d in C.DIMENSIONS]]
    year = int(a.data.groupby("company")["fiscal_year"].max().min())
    comp = comparison_table(a.ratios, a.scores, year)

    stress = []
    for company, g in a.data.groupby("company"):
        y = int(g["fiscal_year"].max())
        try:
            s = run_stress(a.data, company, y, scenarios)
            s.insert(0, "fiscal_year", y)
            s.insert(0, "company", company)
            stress.append(s)
        except ValueError as e:  # e.g. revenue missing: report instead of failing the whole workbook
            stress.append(pd.DataFrame([{"company": company, "fiscal_year": y, "scenario": f"not run: {e}"}]))
    stress = pd.concat(stress, ignore_index=True)
    stress = stress[[c for c in stress.columns if not c.endswith("__status")]]

    about = pd.DataFrame({"Item": ["Data status", "Disclaimer", "Units", "Scoring weights", "Generated by"],
                          "Value": [C.SYNTHETIC_NOTICE if a.synthetic else "Real company data (see data/sources.csv)",
                                    C.DISCLAIMER,
                                    "; ".join(sorted({f"{r.company}: {r.currency} {r.units}"
                                                      for r in a.data.drop_duplicates('company').itertuples()})),
                                    ", ".join(f"{k} {v:.0%}" for k, v in C.ScoringConfig().weights.items()),
                                    "CorporateRisk excel_export.py"]})

    sheets = {
        "About": (about, set(), set(), set()),
        "Raw_Financial_Data": (a.data, set(), set(), money),
        "Calculated_Ratios": (ratios, pct, ratio_keys, money),
        "Ratio_Flags": (a.flags, set(), set(), set()),
        "Health_Scores": (scores, {"weight_coverage"}, set(), set()),
        "Altman_Z": (a.altman, set(), {"z_score", "X1", "X2", "X3", "X4", "X5"}, set()),
        "Company_Comparison": (comp, set(), set(), set()),
        "Stress_Testing": (stress, {"revenue_change", "interest_change", "tax_rate_used", "operating_margin",
                                    "net_profit_margin", "ocf_to_debt", "fcf_to_debt"},
                           {"interest_coverage", "net_debt_to_ebitda", "ebitda_margin_change"}, money),
        "Validation": (a.validation, set(), set(), set()),
    }
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        for name, (df, p, r, m) in sheets.items():
            start = 2 if a.synthetic and name != "About" else 1
            df.to_excel(xw, sheet_name=name, index=False, startrow=start - 1)
            ws = xw.sheets[name]
            if start == 2:
                ws.cell(row=1, column=1, value=C.SYNTHETIC_NOTICE).font = BANNER_FONT
            _format_sheet(ws, df, p, r, m, start_row=start)
        xw.sheets["About"].column_dimensions["B"].width = 110
        for row in xw.sheets["About"].iter_rows(min_row=2):
            row[1].alignment = Alignment(wrap_text=True, vertical="top")
    return path
